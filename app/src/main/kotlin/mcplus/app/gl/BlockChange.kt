package mcplus.app.gl

/**
 * Когда обновление блока означает «блок исчез».
 *
 * Осколки и звук ломания играются не только для своих ударов: сервер присылает обновление
 * блока и чужому игроку, и тому, кто рядом с взрывом, и любому `setblock`. Раньше это было
 * условием `before != 0 && after == 0`, размазанным по обработчику пакетов; здесь оно
 * вынесено, чтобы проверяться тестом и чтобы не потеряться при следующей правке.
 */
object BlockChange {

    /**
     * Появился ли на месте блока воздух: только тогда нужны осколки и звук ломания.
     *
     * @param before состояние блока до обновления (0 — воздух).
     * @param after состояние после.
     */
    fun isRemoval(before: Int, after: Int): Boolean = before != 0 && after == 0

    /** Поставили блок: для этого звук и осколки не нужны. */
    fun isPlacement(before: Int, after: Int): Boolean = before == 0 && after != 0
}
