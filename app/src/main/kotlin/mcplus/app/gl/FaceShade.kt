package mcplus.app.gl

/**
 * Яркость граней блока — как в ванили (`LevelRenderer.getShade`).
 *
 * В игре грани освещены по-разному: верхняя полностью, нижняя вполовину, северная и южная
 * на 0,8, восточная и западная на 0,6. У нас было наоборот: восток и запад ярче севера
 * и юга (0,78 против 0,62), из-за чего блоки выглядели «подсвеченными сбоку».
 *
 * Точные числа взяты из ванильной таблицы (0,5 / 1,0 / 0,8 / 0,6). Сверить их по байткоду
 * не удалось: множители размазаны по шейдерам и `BlockModelLighter`, поэтому тест ниже
 * держит **порядок** яркостей, а не сами константы — порядок и есть то, что видно глазом.
 */
object FaceShade {

    const val UP = 1.0f
    const val DOWN = 0.5f
    const val NORTH = 0.8f
    const val SOUTH = 0.8f
    const val EAST = 0.6f
    const val WEST = 0.6f

    /** Какая грань ярче: верх, затем север/юг, затем восток/запад, ниже всех низ. */
    fun ordered(): Boolean =
        UP > NORTH && NORTH > EAST && EAST > DOWN && NORTH == SOUTH && EAST == WEST
}
